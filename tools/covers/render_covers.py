class CoverRenderer:
    """Draws one `Cover` onto one image. One instance per cover."""

    # The headline starts here and shrinks until the title block clears the
    # footer, so a longer headline can never push type off the artwork.
    HEADLINE_MAX = 104
    HEADLINE_MIN = 60

    def __init__(self, cover: Cover) -> None:
        self.cover = cover
        self.image = Image.new("RGB", (W, H), cover.field)
        self.draw = ImageDraw.Draw(self.image)

    # -- field ------------------------------------------------------------

    def _field(self) -> None:
        """
        A diagonal gradient from the cover's own colour into a deeper corner,
        plus a scrim up the bottom third.

        Computed on a 64x64 tile and scaled up: a per-pixel loop over 1.92M
        pixels is pointless when the result is a smooth ramp, and BICUBIC gives
        a cleaner one than banding would.
        """
        base = self.cover.field
        deep = tuple(int(c * 0.46) for c in base)
        tile = Image.new("RGB", (64, 64))
        px = tile.load()
        for y in range(64):
            for x in range(64):
                # Distance along the diagonal, weighted toward the vertical so
                # the top edge keeps the header legible.
                t = min(1.0, (x / 64 * 0.35 + y / 64 * 0.65))
                px[x, y] = tuple(int(base[i] + (deep[i] - base[i]) * t) for i in range(3))
        self.image.paste(tile.resize((W, H), Image.BICUBIC), (0, 0))

        # The title zone sits on the bottom third, so that third is darkened
        # further — the headline's contrast then does not depend on where the
        # gradient happens to land.
        scrim = Image.new("RGBA", (1, H))
        spx = scrim.load()
        for y in range(H):
            t = max(0.0, (y - H * 0.5) / (H * 0.5))
            spx[0, y] = (0, 0, 0, int(118 * t * t))
        self.image.paste(
            Image.alpha_composite(self.image.convert("RGBA"), scrim.resize((W, H))).convert("RGB"),
            (0, 0),
        )

    def _tricolour(self, y: float, height: float) -> None:
        """The republic's three colours as a hairline rule, in flag order."""
        for i, colour in enumerate((PH_BLUE, PH_RED, PH_YELLOW)):
            self.draw.rectangle(
                [MARGIN + i * (W - 2 * MARGIN) / 3, y, MARGIN + (i + 1) * (W - 2 * MARGIN) / 3, y + height],
                fill=colour,
            )

    # -- pictogram --------------------------------------------------------

    def _pictogram(self) -> None:
        """Drawn on its own layer so it can be composited at low opacity."""
        layer = Image.new("RGBA", (W, H), (0, 0, 0, 0))
        d = ImageDraw.Draw(layer)
        size = 560
        x0 = (W - size) / 2
        y0 = 408
        self.cover.pictogram(d, (x0, y0, x0 + size, y0 + size), 16, (*GOLD_ON_DARK, 56))
        self.image.paste(
            Image.alpha_composite(self.image.convert("RGBA"), layer).convert("RGB"), (0, 0)
        )

    # -- header -----------------------------------------------------------

    def _header(self) -> None:
        self._tricolour(0, 7)

        y = MARGIN
        draw_tracked(
            self.draw,
            (MARGIN, y),
            "REPUBLIC OF THE PHILIPPINES",
            text(21, 600),
            GOLD_ON_DARK,
            tracking=2.6,
        )
        self.draw.text((MARGIN, y + 34), "Lungsod ng Tanjay", font=display(44, 700), fill=WHITE)
        draw_tracked(
            self.draw,
            (MARGIN, y + 96),
            "City Government · Negros Oriental",
            text(21, 400),
            (0xA9, 0xC0, 0xB6),
            tracking=0.8,
        )
        self.draw.rectangle([MARGIN, y + 140, MARGIN + 92, y + 143], fill=GOLD_BRIGHT)

    def _stamp(self) -> None:
        """
        The SAMPLE stamp, set as a rubber stamp and rotated a few degrees.

        Rotation needs its own layer, which is also what lets the stamp carry a
        slightly translucent ink like a real one.
        """
        bw, bh = 300, 104
        layer = Image.new("RGBA", (bw, bh), (0, 0, 0, 0))
        d = ImageDraw.Draw(layer)
        ink = (*GOLD_ON_DARK, 235)

        d.rounded_rectangle([2, 2, bw - 3, bh - 3], radius=8, outline=ink, width=4)
        big = display(46, 700)
        s = "SAMPLE"
        draw_tracked(d, ((bw - tracked_width(big, s, 5.0)) / 2, 14), s, big, ink, tracking=5.0)
        small = text(17, 600)
        s2 = "FOR DEMONSTRATION"
        draw_tracked(d, ((bw - tracked_width(small, s2, 2.4)) / 2, 70), s2, small, ink, tracking=2.4)

        spun = layer.rotate(-5, expand=True, resample=Image.BICUBIC)
        self.image.paste(spun, (W - MARGIN - spun.width + 14, MARGIN - 6), spun)

    # -- title block ------------------------------------------------------

    def _title(self) -> None:
        """
        The cover's title zone, laid out from a fixed top and verified to clear
        the footer. The headline shrinks and re-wraps until it fits.
        """
        limit = W - 2 * MARGIN
        top = 1010
        floor = H - MARGIN - 86  # above the footer rule and its label

        size = self.HEADLINE_MAX
        while True:
            font = display(size, 700)
            lines = wrap(font, self.cover.headline, limit, tracking=-1.0)
            line_h = size * 1.04
            standfirst_font = text(27, 400)
            sf_lines = wrap(standfirst_font, self.cover.standfirst, limit)
            block = 46 + 52 + len(lines) * line_h + 30 + len(sf_lines) * 36
            if top + block <= floor or size <= self.HEADLINE_MIN:
                break
            size -= 4

        y = top
        draw_tracked(self.draw, (MARGIN, y), self.cover.masthead, text(21, 600), GOLD_ON_DARK, tracking=3.4)
        y += 46

        # Badge: a hairline pill, the way the section tags are set on the site.
        badge_font = text(20, 700)
        bw = tracked_width(badge_font, self.cover.badge, 2.6)
        self.draw.rounded_rectangle(
            [MARGIN, y, MARGIN + bw + 36, y + 38], radius=19, outline=GOLD_BRIGHT, width=2
        )
        draw_tracked(self.draw, (MARGIN + 18, y + 8), self.cover.badge, badge_font, WHITE, tracking=2.6)
        y += 52

        for line in lines:
            draw_tracked(self.draw, (MARGIN, y), line, font, WHITE, tracking=-1.0)
            y += line_h

        y += 14
        self.draw.rectangle([MARGIN, y, MARGIN + 120, y + 3], fill=GOLD_BRIGHT)
        y += 16

        for line in sf_lines:
            self.draw.text((MARGIN, y), line, font=standfirst_font, fill=(0xE4, 0xEF, 0xE9))
            y += 36

    def _footer(self) -> None:
        y = H - MARGIN - 34
        self.draw.rectangle([MARGIN, y, W - MARGIN, y + 1], fill=(0xFF, 0xFF, 0xFF, 0x2E))
        draw_tracked(
            self.draw,
            (MARGIN, y + 12),
            "CITY INFORMATION OFFICE",
            text(19, 600),
            (0xA9, 0xC0, 0xB6),
            tracking=2.2,
        )
        draw_tracked(
            self.draw,
            (W - MARGIN, y + 12),
            "tanjaycity.gov.ph",
            text(19, 400),
            (0xA9, 0xC0, 0xB6),
            tracking=0.6,
            anchor_right=True,
        )
        self._tricolour(H - 7, 7)

    # -- output -----------------------------------------------------------

    def render(self) -> Image.Image:
        self._field()
        self._pictogram()
        self._header()
        self._stamp()
        self._title()
        self._footer()
        return self.image


def to_webp(image: Image.Image, destination: Path) -> int:
    """
    Write the artwork as WebP via `cwebp`, through a PNG that is then removed.

    `cwebp` rather than Pillow's own encoder because the rest of the site's
    artwork was produced with it, and a matched encoder keeps file sizes and
    colour handling consistent across the set.
    """
    png = destination.with_suffix(".png")
    image.save(png)
    try:
        subprocess.run(
            [CWEBP, "-quiet", "-q", WEBP_QUALITY, str(png), "-o", str(destination)],
            check=True,
        )
    finally:
        png.unlink(missing_ok=True)
    return destination.stat().st_size


def main(covers: Iterable[Cover] = COVERS) -> int:
    if not Path(CWEBP).exists():
        print(f"cwebp not found at {CWEBP} — install it with `brew install webp`.", file=sys.stderr)
        return 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for cover in covers:
        destination = OUT_DIR / f"{cover.name}.webp"
        size = to_webp(CoverRenderer(cover).render(), destination)
        print(f"{destination.relative_to(ROOT)}  {W}x{H}  {size:,} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
