#!/usr/bin/env python3
"""
Source of the portrait sample covers in `database/seeders/assets/posters/`.

WHY THIS FILE EXISTS
--------------------
The "Latest updates" band on the landing page is laid out around a portrait
cover, the way a city magazine's cover is set beside its blurb. The seeder
needs four of those covers before the City Information Office has drawn any,
and committed binary artwork that nobody can regenerate is artwork nobody can
correct — a typo, a palette change or a new size would mean redrawing by hand
in an image editor and hoping the next one matches. So the artwork is generated
from this script, the script is committed next to it, and the covers are
regenerated by re-running it.

EVERY COVER IS STAMPED SAMPLE. These are demonstration records: they carry a
"SAMPLE / FOR DEMONSTRATION" stamp and a standfirst that says in words that
nothing is being announced, because a plausible-looking city cover that escaped
into production would otherwise be indistinguishable from a real one. The
drawings are flat line pictograms — no photographs, no city seal, no invented
logos or conferring bodies.

The palette, the type and the republic header are the same ones the existing
16:9 demo posters use, recomposed to 3:4 portrait, so the band reads as part of
the same set.

USAGE
-----
    python3 tools/covers/render_covers.py

Requires Pillow and `cwebp`. See README.md in this directory.
"""

from __future__ import annotations

import glob
import math
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Iterable, Sequence

from PIL import Image, ImageDraw, ImageFont

# --- Where things live ------------------------------------------------------

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "database" / "seeders" / "assets" / "posters"
FONT_CACHE = Path(__file__).resolve().parent / ".fontcache"
CWEBP = shutil.which("cwebp") or "/opt/homebrew/bin/cwebp"
WEBP_QUALITY = "82"

# 3:4 portrait. The band's cover slot is portrait, and a magazine cover is the
# reference, so the artwork is drawn at the aspect it is displayed at rather
# than cropped into it by the browser.
W, H = 1200, 1600
MARGIN = 86

# --- Palette: the site's own tokens ----------------------------------------
# Lifted from resources/css/tokens.css. Kept as literals here because this
# script runs outside the build and cannot read CSS custom properties; if a
# token changes there, change it here and re-render.

PRIMARY = (0x0F, 0x5C, 0x45)  # --primary
PRIMARY_900 = (0x07, 0x30, 0x1F)  # --primary-900
SEA_700 = (0x0D, 0x5F, 0x6E)  # --sea-700
MASTHEAD_FROM = (0x07, 0x3B, 0x2D)  # --masthead-from

GOLD_BRIGHT = (0xB8, 0x83, 0x2A)  # --gold-bright
GOLD_ON_DARK = (0xE3, 0xB9, 0x71)  # --gold-on-dark
WHITE = (0xFF, 0xFF, 0xFF)

PH_BLUE = (0x00, 0x38, 0xA8)
PH_RED = (0xCE, 0x11, 0x26)
PH_YELLOW = (0xFC, 0xD1, 0x16)

Color = tuple[int, int, int]
Box = tuple[float, float, float, float]


# --- Type -------------------------------------------------------------------


def _font_candidates(pattern: str, system: Sequence[str]) -> list[Path]:
    """
    The project's real faces first, macOS system faces as the fallback.

    The project's Archivo and Source Sans 3 only exist as woff2 under
    `public/build/assets/`, which is a build artefact and gitignored — on a
    fresh clone they are simply not there until `npm run build` has run. Pillow
    cannot read woff2 either, so each one is converted to a TTF in .fontcache
    (also gitignored) the first time it is needed. If fontTools is missing or
    the build has not run, rendering falls back to the system faces rather than
    failing: the covers are then a shade off the site's typography, which is
    better than no covers at all.
    """
    found = [Path(p) for p in sorted(glob.glob(str(ROOT / "public" / "build" / "assets" / pattern)))]
    return found + [Path(p) for p in system]


def _to_ttf(woff2: Path) -> Path | None:
    """Convert one woff2 to a cached TTF, or None if that is not possible."""
    cached = FONT_CACHE / (woff2.stem + ".ttf")
    if cached.exists():
        return cached
    try:
        from fontTools.ttLib import TTFont
    except ImportError:
        return None
    try:
        FONT_CACHE.mkdir(parents=True, exist_ok=True)
        face = TTFont(str(woff2))
        face.flavor = None
        face.save(str(cached))
        return cached
    except Exception:  # a corrupt or partial build artefact is not fatal
        return None


def load_font(pattern: str, system: Sequence[str], size: int) -> ImageFont.FreeTypeFont:
    """
    Resolve one face at one size through a single ordered candidate list.

    Every call goes through here, so a missing font degrades the whole render
    consistently instead of crashing halfway down one cover.
    """
    for candidate in _font_candidates(pattern, system):
        path = _to_ttf(candidate) if candidate.suffix == ".woff2" else candidate
        if path is None or not Path(path).exists():
            continue
        try:
            return ImageFont.truetype(str(path), size)
        except OSError:
            continue
    return ImageFont.load_default(size)


HELVETICA = ("/System/Library/Fonts/HelveticaNeue.ttc", "/System/Library/Fonts/Helvetica.ttc")


def display(size: int, weight: int = 700) -> ImageFont.FreeTypeFont:
    """Archivo — the site's display face, used for the headline and the city name."""
    return load_font(f"archivo-{weight}-normal-*.woff2", HELVETICA, size)


def text(size: int, weight: int = 400) -> ImageFont.FreeTypeFont:
    """Source Sans 3 — the site's text face, for labels, badges and standfirsts."""
    return load_font(f"source-sans-3-{weight}-normal-*.woff2", HELVETICA, size)


def tracked_width(font: ImageFont.FreeTypeFont, s: str, tracking: float) -> float:
    """Advance width of `s` with letterspacing applied between characters."""
    if not s:
        return 0.0
    return sum(font.getlength(ch) for ch in s) + tracking * (len(s) - 1)


def draw_tracked(
    draw: ImageDraw.ImageDraw,
    xy: tuple[float, float],
    s: str,
    font: ImageFont.FreeTypeFont,
    fill: Color | tuple[int, int, int, int],
    tracking: float = 0.0,
    anchor_right: bool = False,
) -> None:
    """
    Letterspaced text, drawn a character at a time.

    Pillow has no tracking control, and the small uppercase labels on these
    covers — the republic header, the badge, the footer — are letterspaced in
    the site's own stylesheet. Setting them solid would be the one detail that
    gave the artwork away as not belonging to the set.
    """
    x, y = xy
    if anchor_right:
        x -= tracked_width(font, s, tracking)
    for ch in s:
        draw.text((x, y), ch, font=font, fill=fill)
        x += font.getlength(ch) + tracking


def wrap(font: ImageFont.FreeTypeFont, s: str, limit: float, tracking: float = 0.0) -> list[str]:
    """Greedy word wrap measured with the real face, not an estimated char count."""
    lines: list[str] = []
    current = ""
    for word in s.split():
        trial = f"{current} {word}".strip()
        if current and tracked_width(font, trial, tracking) > limit:
            lines.append(current)
            current = word
        else:
            current = trial
    if current:
        lines.append(current)
    return lines


# --- Pictograms -------------------------------------------------------------
# Flat single-stroke line drawings in the Lucide idiom, each taking a box and
# drawing into it. `joint="curve"` is what gives a polyline Lucide's rounded
# corners. They are the only illustration on the field and they sit at low
# opacity behind the type, so they read as a watermark rather than competing
# with the headline.


def _sine(x0: float, x1: float, y: float, amp: float, cycles: float, steps: int = 96) -> list[tuple[float, float]]:
    return [
        (x0 + (x1 - x0) * i / steps, y + amp * math.sin(2 * math.pi * cycles * i / steps))
        for i in range(steps + 1)
    ]


def book(d: ImageDraw.ImageDraw, b: Box, w: int, c: tuple[int, int, int, int]) -> None:
    """An open book / magazine spread."""
    x0, y0, x1, y1 = b
    bw, bh = x1 - x0, y1 - y0
    cx = x0 + bw / 2
    gap = bw * 0.035

    for side in (-1, 1):
        inner = cx + side * gap
        outer = cx + side * bw * 0.5
        d.line(
            [
                (inner, y0 + bh * 0.08),
                (outer, y0 + bh * 0.2),
                (outer, y1 - bh * 0.06),
                (inner, y1 - bh * 0.18),
            ],
            fill=c,
            width=w,
            joint="curve",
        )
        for i in range(3):
            ly = y0 + bh * (0.36 + i * 0.16)
            d.line(
                [(inner + side * bw * 0.06, ly), (inner + side * bw * 0.36, ly + side * -bh * 0.015)],
                fill=c,
                width=max(2, w // 2),
            )

    d.line([(cx, y0 + bh * 0.08), (cx, y1 - bh * 0.18)], fill=c, width=w)


def store(d: ImageDraw.ImageDraw, b: Box, w: int, c: tuple[int, int, int, int]) -> None:
    """A market stall: awning over a storefront."""
    x0, y0, x1, y1 = b
    bw, bh = x1 - x0, y1 - y0
    roof = y0 + bh * 0.3

    # Roof: a shallow trapezoid, wider than the body it covers.
    d.line(
        [(x0, roof), (x0 + bw * 0.12, y0 + bh * 0.1), (x1 - bw * 0.12, y0 + bh * 0.1), (x1, roof)],
        fill=c,
        width=w,
        joint="curve",
    )
    # Scalloped awning edge.
    scallops = 5
    sw = bw / scallops
    for i in range(scallops):
        d.arc(
            [x0 + i * sw, roof - sw * 0.42, x0 + (i + 1) * sw, roof + sw * 0.42],
            start=0,
            end=180,
            fill=c,
            width=w,
        )
    # Body, with a door.
    body_top = roof + sw * 0.42
    d.line(
        [(x0 + bw * 0.07, body_top), (x0 + bw * 0.07, y1), (x1 - bw * 0.07, y1), (x1 - bw * 0.07, body_top)],
        fill=c,
        width=w,
        joint="curve",
    )
    d.line(
        [
            (x0 + bw * 0.36, y1),
            (x0 + bw * 0.36, y1 - bh * 0.28),
            (x1 - bw * 0.36, y1 - bh * 0.28),
            (x1 - bw * 0.36, y1),
        ],
        fill=c,
        width=w,
        joint="curve",
    )


def river(d: ImageDraw.ImageDraw, b: Box, w: int, c: tuple[int, int, int, int]) -> None:
    """A bridge over water: deck and piers above three wave lines."""
    x0, y0, x1, y1 = b
    bw, bh = x1 - x0, y1 - y0
    deck = y0 + bh * 0.34

    d.line([(x0, deck), (x1, deck)], fill=c, width=w)
    # Two arches under the deck.
    for i in (0, 1):
        ax0 = x0 + bw * (0.07 + i * 0.47)
        d.arc([ax0, deck - bh * 0.1, ax0 + bw * 0.39, deck + bh * 0.26], start=180, end=360, fill=c, width=w)
    # Piers.
    for fx in (0.07, 0.5, 0.93):
        d.line([(x0 + bw * fx, deck), (x0 + bw * fx, deck + bh * 0.2)], fill=c, width=w)
    # Railing posts.
    for i in range(7):
        px = x0 + bw * (0.06 + i * 0.147)
        d.line([(px, deck), (px, deck - bh * 0.1)], fill=c, width=max(2, w // 2))
    d.line([(x0 + bw * 0.04, deck - bh * 0.1), (x1 - bw * 0.04, deck - bh * 0.1)], fill=c, width=max(2, w // 2))

    for i in range(3):
        d.line(
            _sine(x0, x1, y1 - bh * (0.22 - i * 0.11), bh * 0.045, 1.6),
            fill=c,
            width=w,
            joint="curve",
        )


def monitor(d: ImageDraw.ImageDraw, b: Box, w: int, c: tuple[int, int, int, int]) -> None:
    """A screen with a small network of linked nodes on it."""
    x0, y0, x1, y1 = b
    bw, bh = x1 - x0, y1 - y0
    screen = (x0, y0, x1, y0 + bh * 0.72)

    d.rounded_rectangle(screen, radius=bw * 0.05, outline=c, width=w)
    # Stand.
    d.line([(x0 + bw * 0.5, screen[3]), (x0 + bw * 0.5, y1 - bh * 0.06)], fill=c, width=w)
    d.line([(x0 + bw * 0.28, y1 - bh * 0.06), (x1 - bw * 0.28, y1 - bh * 0.06)], fill=c, width=w, joint="curve")

    # Three linked nodes inside the screen.
    nodes = [
        (x0 + bw * 0.28, y0 + bh * 0.24),
        (x0 + bw * 0.68, y0 + bh * 0.2),
        (x0 + bw * 0.5, y0 + bh * 0.52),
    ]
    for a in range(len(nodes)):
        d.line([nodes[a], nodes[(a + 1) % len(nodes)]], fill=c, width=max(2, w // 2))
    r = bw * 0.05
    for nx, ny in nodes:
        d.ellipse([nx - r, ny - r, nx + r, ny + r], outline=c, width=w)


