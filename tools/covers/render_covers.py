@dataclass(frozen=True)
class Cover:
    """The content of one sample cover, and nothing about how it is drawn."""

    name: str
    badge: str
    headline: str
    standfirst: str
    masthead: str
    field: Color
    pictogram: Callable[[ImageDraw.ImageDraw, Box, int, tuple[int, int, int, int]], None]


